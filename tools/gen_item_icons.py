N = 12
W = H = N * SCALE
c = ['/* Generated by tools/gen_item_icons.py - do not edit */',
     '#ifdef BOARD_MORNING_BOARD', '#include "lvgl.h"', '']
h = ['#pragma once', '/* Generated by tools/gen_item_icons.py */',
     '#include <lvgl.h>', '#ifdef __cplusplus', 'extern "C" {', '#endif']
for name, grid in ICONS.items():
    assert len(grid) == N and all(len(r) == N for r in grid), name
    data = []
    for row in grid:
        line = []
        for ch in row:
            if ch == '.':
                px = [0, 0, 0, 0]
            else:
                r, g, b = PAL[ch]
                px = [b, g, r, 0xFF]      # ARGB8888 little-endian: B G R A
            line += px * SCALE
        data += line * SCALE
    c.append(f'static const uint8_t mb_ic_{name}_data[{len(data)}] = {{')
    for i in range(0, len(data), 24):
        c.append('    ' + ','.join(f'0x{v:02X}' for v in data[i:i+24]) + ',')
    c.append('};')
    c.append(f'const lv_image_dsc_t mb_ic_{name} = {{')
