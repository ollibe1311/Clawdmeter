#!/usr/bin/env python3
"""Generate 28x28 pixel-art weather icons (14x14 grid, 2x scale) as LVGL 9
ARGB8888 image descriptors: firmware/src/morning_weather_icons.{c,h}."""
import os
SCALE = 2
PAL = {
    'Y': (0xF2, 0xB3, 0x3D),  # sun / bolt
    'O': (0xD8, 0x76, 0x56),  # Clawd orange accent (sun core)
    'G': (0x7A, 0x7A, 0x7A),  # cloud outline
    'W': (0xFF, 0xFF, 0xFF),  # light cloud
    'D': (0xA7, 0xAF, 0xB9),  # rain/storm cloud
    'B': (0x3B, 0x82, 0xF6),  # rain drops
    'F': (0x9C, 0xA3, 0xAF),  # fog lines
}
CLOUD_W = [
    ".....GGGG.....",
    "....GWWWWG....",
    "..GGWWWWWWG...",
    ".GWWWWWWWWWGG.",
    "GWWWWWWWWWWWWG",
    "GWWWWWWWWWWWWG",
    ".GGGGGGGGGGGG.",
]
CLOUD_D = [r.replace('W', 'D') for r in CLOUD_W]
B = ".............."
ICONS = {
    'sun': [
        "......Y.......",
        "..Y...Y...Y...",
        "...Y.....Y....",
        ".....YYY......",
        "....YOOOY.....",
        "...YOOOOOY....",
        "YY.YOOOOOY.YY.",
        "...YOOOOOY....",
        "....YOOOY.....",
        ".....YYY......",
        "...Y.....Y....",
        "..Y...Y...Y...",
        "......Y.......",
        B,
    ],
    'partly': [
        "...Y..........",
        ".Y.Y.Y........",
        "..YOY.........",
        "YYOOOYY.......",
        "..YOYGGGG.....",
        ".Y.YGWWWWG....",
        "...GWWWWWWGG..",
        "..GWWWWWWWWWG.",
        ".GWWWWWWWWWWWG",
        ".GWWWWWWWWWWWG",
        "..GGGGGGGGGGG.",
        B, B, B,
    ],
    'cloud': [B, B, B] + CLOUD_W + [B, B, B, B],
    'rain': [B] + CLOUD_D + [
        B,
        "..B...B...B...",
        ".B...B...B....",
        B,
        "...B...B...B..",
        "..B...B...B...",
    ],
    'storm': [B] + CLOUD_D + [
        "......YY......",
        ".....YY.......",
        "....YYYYY.....",
        "......YY......",
        ".....YY.......",
        "....Y.........",
    ],
    'fog': [B] + CLOUD_W + [
        "FFFFFFFFFFF...",
        B,
        "...FFFFFFFFFFF",
        B,
        ".FFFFFFFFFFF..",
        B,
    ],
}
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, '..', 'firmware', 'src')
W = H = 14 * SCALE
c = ['/* Generated by tools/gen_weather_icons.py - do not edit */',
     '#ifdef BOARD_MORNING_BOARD', '#include "lvgl.h"', '']
h = ['#pragma once', '/* Generated by tools/gen_weather_icons.py */',
     '#include <lvgl.h>', '#ifdef __cplusplus', 'extern "C" {', '#endif']
for name, grid in ICONS.items():
    assert len(grid) == 14 and all(len(r) == 14 for r in grid), name
    data = []
    for row in grid:
        line = []
        for ch in row:
            if ch == '.':
                px = [0, 0, 0, 0]
            else:
                r, g, b = PAL[ch]
                px = [b, g, r, 0xFF]      # ARGB8888 little-endian: B G R A
            line += px * SCALE
        data += line * SCALE
    c.append(f'static const uint8_t mb_wx_{name}_data[{len(data)}] = {{')
    for i in range(0, len(data), 24):
        c.append('    ' + ','.join(f'0x{v:02X}' for v in data[i:i+24]) + ',')
    c.append('};')
    c.append(f'const lv_image_dsc_t mb_wx_{name} = {{')
    c.append(f'    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, '
             f'.flags = 0, .w = {W}, .h = {H}, .stride = {W*4} }},')
    c.append(f'    .data_size = sizeof(mb_wx_{name}_data),')
    c.append(f'    .data = mb_wx_{name}_data,')
    c.append('};\n')
    h.append(f'extern const lv_image_dsc_t mb_wx_{name};')
c.append('#endif /* BOARD_MORNING_BOARD */')
h += ['#ifdef __cplusplus', '}', '#endif']
open(os.path.join(out, 'morning_weather_icons.c'), 'w').write('\n'.join(c) + '\n')
open(os.path.join(out, 'morning_weather_icons.h'), 'w').write('\n'.join(h) + '\n')
print('ok', list(ICONS))
